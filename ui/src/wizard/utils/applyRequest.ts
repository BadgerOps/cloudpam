import type { SchemaApplyRequest, SchemaPoolEntry } from '../../api/types'
import type { SchemaNode } from './cidr'

export function flattenForApply(node: SchemaNode, parentRef: string | null): SchemaPoolEntry[] {
  const entry: SchemaPoolEntry = {
    ref: node.id,
    name: node.name,
    cidr: node.cidr,
    type: node.type,
    ...(parentRef === null ? {} : { parent_ref: parentRef }),
    description: 'Generated by Schema Planner',
  }

  const result: SchemaPoolEntry[] = [entry]
  for (const child of node.children) {
    result.push(...flattenForApply(child, node.id))
  }
  return result
}

/** The body `POST /api/v1/schema/apply` receives for a planned schema. */
export function buildApplyRequest(schema: SchemaNode, skipConflicts = false): SchemaApplyRequest {
  return {
    pools: flattenForApply(schema, null),
    status: 'planned',
    tags: { schema_planner: 'true' },
    skip_conflicts: skipConflicts,
  }
}
