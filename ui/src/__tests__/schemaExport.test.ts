import { describe, expect, it } from 'vitest'
import { parse } from 'yaml'
import { EXPORT_FORMATS, schemaToJson, schemaToYaml } from '../wizard/utils/export'
import { toYaml } from '../wizard/utils/yaml'
import type { SchemaNode } from '../wizard/utils/cidr'

const GENERATED_AT = '2026-11-02T00:00:00.000Z'

const schema: SchemaNode = {
  id: 'root',
  name: 'Global',
  cidr: '10.0.0.0/8',
  type: 'supernet',
  children: [
    {
      id: 'r1',
      name: 'us-east-1',
      cidr: '10.0.0.0/12',
      type: 'region',
      children: [{ id: 'e1', name: 'prod', cidr: '10.0.0.0/16', type: 'environment', children: [] }],
    },
  ],
}

// The body POST /api/v1/schema/apply accepts, written out by hand so the
// exports are checked against the API contract rather than against each other.
const applyBody = {
  pools: [
    { ref: 'root', name: 'Global', cidr: '10.0.0.0/8', type: 'supernet', description: 'Generated by Schema Planner' },
    {
      ref: 'r1',
      name: 'us-east-1',
      cidr: '10.0.0.0/12',
      type: 'region',
      parent_ref: 'root',
      description: 'Generated by Schema Planner',
    },
    {
      ref: 'e1',
      name: 'prod',
      cidr: '10.0.0.0/16',
      type: 'environment',
      parent_ref: 'r1',
      description: 'Generated by Schema Planner',
    },
  ],
  status: 'planned',
  tags: { schema_planner: 'true' },
  skip_conflicts: false,
}

describe('schemaToJson', () => {
  it('is the exact schema/apply request body', () => {
    expect(JSON.parse(schemaToJson(schema))).toEqual(applyBody)
  })
})

describe('schemaToYaml', () => {
  it('round-trips through a YAML parser to the schema/apply request body', () => {
    expect(parse(schemaToYaml(schema, GENERATED_AT))).toEqual(applyBody)
  })

  it('says what the file is and when it was generated', () => {
    const yaml = schemaToYaml(schema, GENERATED_AT)
    expect(yaml).toContain('POST /api/v1/schema/apply')
    expect(yaml).toContain(GENERATED_AT)
  })
})

describe('toYaml', () => {
  // Pool names are user input, so every scalar has to survive YAML's own
  // syntax and must not be promoted to a bool, number or null.
  it('round-trips strings that YAML would otherwise read as syntax or other types', () => {
    const value = {
      pools: [
        {
          name: 'a: b # c',
          cidr: '- leading dash',
          type: 'true',
          ref: '123',
          description: 'line\nbreak "quoted" \'single\' {flow} [seq] ~ unicode ✓',
        },
      ],
      tags: { 'odd key: here': 'x', y: 'reserved key' },
      empty_list: [],
      empty_map: {},
      nested: [[1, 2.5, -3], [{ k: 'v' }], 'plain'],
      flag: false,
      none: null,
    }
    expect(parse(toYaml(value))).toEqual(value)
  })

  it('quotes keys a YAML 1.1 parser would read as booleans', () => {
    expect(toYaml({ true: 1, on: 2 })).toBe('"true": 1\n"on": 2\n')
  })

  it('drops undefined properties and non-finite numbers like JSON.stringify', () => {
    const value = { a: 1, b: undefined, c: Number.POSITIVE_INFINITY }
    expect(parse(toYaml(value))).toEqual(JSON.parse(JSON.stringify(value)))
  })
})

describe('EXPORT_FORMATS', () => {
  it('gives every format a distinct filename and a rendering of the schema', () => {
    const filenames = new Set<string>()
    for (const spec of Object.values(EXPORT_FORMATS)) {
      filenames.add(spec.filename)
      expect(spec.render(schema, GENERATED_AT)).toContain('10.0.0.0/8')
    }
    expect(filenames.size).toBe(Object.keys(EXPORT_FORMATS).length)
  })
})
