import { fireEvent, render, screen } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { parse } from 'yaml'
import SchemaPlanner from '../wizard/SchemaPlanner'
import type { SchemaNode } from '../wizard/utils/cidr'

const mocks = vi.hoisted(() => ({
  generated: { schema: null as unknown, error: null as string | null },
}))

vi.mock('../wizard/hooks/useSchemaGenerator', () => ({
  useSchemaGenerator: () => mocks.generated,
}))

vi.mock('../wizard/hooks/useConflictChecker', () => ({
  useConflictChecker: () => ({ conflicts: [], loading: false, error: null }),
}))

vi.mock('../wizard/hooks/useApplySchema', () => ({
  useApplySchema: () => ({ result: null, loading: false, error: null, apply: vi.fn() }),
}))

const schema: SchemaNode = {
  id: 'root',
  name: 'Root',
  type: 'supernet',
  cidr: '10.0.0.0/8',
  children: [{ id: 'r1', name: 'us-east-1', type: 'region', cidr: '10.0.0.0/12', children: [] }],
}

const applyBody = {
  pools: [
    { ref: 'root', name: 'Root', cidr: '10.0.0.0/8', type: 'supernet', description: 'Generated by Schema Planner' },
    {
      ref: 'r1',
      name: 'us-east-1',
      cidr: '10.0.0.0/12',
      type: 'region',
      parent_ref: 'root',
      description: 'Generated by Schema Planner',
    },
  ],
  status: 'planned',
  tags: { schema_planner: 'true' },
  skip_conflicts: false,
}

const downloads: { name: string; blob: Blob }[] = []

function readText(blob: Blob): Promise<string> {
  return new Promise((resolve) => {
    const reader = new FileReader()
    reader.onload = () => resolve(reader.result as string)
    reader.readAsText(blob)
  })
}

function openPreview() {
  render(<SchemaPlanner />)
  fireEvent.click(screen.getByRole('button', { name: /Enterprise Multi-Region/ }))
  for (let i = 0; i < 3; i++) fireEvent.click(screen.getByRole('button', { name: 'Continue' }))
}

describe('SchemaPlanner export downloads', () => {
  beforeEach(() => {
    localStorage.clear()
    downloads.length = 0
    mocks.generated = { schema, error: null }
    let pending: Blob | null = null
    Object.assign(URL, {
      createObjectURL: (blob: Blob) => {
        pending = blob
        return 'blob:cloudpam-test'
      },
      revokeObjectURL: () => {},
    })
    vi.spyOn(HTMLAnchorElement.prototype, 'click').mockImplementation(function (this: HTMLAnchorElement) {
      downloads.push({ name: this.download, blob: pending as unknown as Blob })
    })
  })

  afterEach(() => {
    vi.restoreAllMocks()
  })

  it('downloads the schema/apply request body as JSON', async () => {
    openPreview()
    fireEvent.click(screen.getByRole('button', { name: 'Export JSON' }))
    expect(downloads).toHaveLength(1)
    expect(downloads[0].name).toBe('cloudpam-schema.json')
    expect(downloads[0].blob.type).toBe('application/json')
    expect(JSON.parse(await readText(downloads[0].blob))).toEqual(applyBody)
  })

  it('downloads the same body as YAML', async () => {
    openPreview()
    fireEvent.click(screen.getByRole('button', { name: 'Export YAML' }))
    expect(downloads).toHaveLength(1)
    expect(downloads[0].name).toBe('cloudpam-schema.yaml')
    expect(downloads[0].blob.type).toBe('application/yaml')
    expect(parse(await readText(downloads[0].blob))).toEqual(applyBody)
  })

  it('still downloads Terraform and CSV', async () => {
    openPreview()
    fireEvent.click(screen.getByRole('button', { name: 'Export Terraform' }))
    fireEvent.click(screen.getByRole('button', { name: 'Export CSV' }))
    expect(downloads.map((d) => d.name)).toEqual(['cloudpam-schema.tf', 'cloudpam-schema.csv'])
    expect(await readText(downloads[0].blob)).toContain('resource "cloudpam_pool"')
    expect(await readText(downloads[1].blob)).toContain('us-east-1,10.0.0.0/12,region,Root')
  })
})
